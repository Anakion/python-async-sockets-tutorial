# 01_simple_socket.py — собираем вместе, строка за строкой
#
# Что такое сокет?
#
#   [Программа A]               [Программа B]
#       Сокет A ════════════════ Сокет B
#         🔌   ← TCP тоннель →    🔌
#
#   Сокет — "ручка" на конце соединения.
#   Ты выбираешь протокол (TCP или UDP) при создании сокета.
#   ОС реализует выбранный протокол и управляет тоннелем.
#
#   socket(AF_INET, SOCK_STREAM) → TCP  (надёжно, по порядку)
#   socket(AF_INET, SOCK_DGRAM)  → UDP  (быстро, без гарантий)


import socket  # стандартная библиотека Python для работы с сетью

sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
#
# ─────────────────────────────────────────────────
# Что такое IPv4?
#
#   IP-адрес — уникальный номер каждого устройства.
#   Как почтовый адрес, но для компьютеров.
#
#   IPv4 адрес выглядит так:
#
#   192  .  168  .   1  .  100
#    │        │       │     │
#    └────────┴───────┴─────┘
#      4 числа, каждое от 0 до 255
#
#   Примеры:
#   127.0.0.1    ← твой собственный компьютер (localhost)
#   192.168.1.1  ← домашний роутер
#   8.8.8.8      ← DNS сервер Google
#
#   Каждый сайт — тоже IP, просто с именем:
#   "google.com"  →  142.250.74.46   (DNS переводит имя в адрес)
#   "httpbin.org" →  54.208.105.209
#
# ─────────────────────────────────────────────────
# Что такое AF_INET?
#
#   AF = Address Family (семейство адресов)
#   Сокет должен знать в каком формате будут адреса:
#
#   AF_INET   → IPv4  (192.168.x.x)         ← используем это
#   AF_INET6  → IPv6  (2001:db8::1)         ← новый стандарт
#   AF_UNIX   → путь к файлу (/tmp/my.sock) ← локально без сети
#
#   IPv6 появился потому что IPv4 адресов (~4 млрд) стало не хватать.
#
# ─────────────────────────────────────────────────
# SOCK_STREAM vs SOCK_DGRAM
#
#   SOCK_STREAM → TCP (надёжная доставка, порядок сохраняется)
#   SOCK_DGRAM  → UDP (быстро, но без гарантий)
#
# Сокет создан, но НЕ подключён — как купить телефон,
# но ещё не позвонить.
# ─────────────────────────────────────────────────

HOST = "httpbin.org"
PORT = 80
#
# ─────────────────────────────────────────────────
# HOST — доменное имя сервера.
#
#   Компьютеры не понимают имена — только числа (IP).
#   Поэтому есть DNS — "телефонная книга" интернета:
#
#   "httpbin.org"  →  DNS запрос  →  54.208.105.209
#
#   Перевод происходит автоматически при вызове connect().
#
# ─────────────────────────────────────────────────
# PORT — номер порта.
#
#   IP-адрес = адрес здания
#   Порт     = номер квартиры
#
#   На одном IP работает много программ — каждая на своём порту:
#
#   54.208.105.209 : 80   ← HTTP   (наш случай)
#   54.208.105.209 : 443  ← HTTPS
#   54.208.105.209 : 22   ← SSH
#   54.208.105.209 : 25   ← Email (SMTP)
#
#   Порты 0–1023 зарезервированы системой.
#   Порт 80 — стандартный для HTTP (без шифрования).
#
# ─────────────────────────────────────────────────
# Что происходит на стороне httpbin.org?
#
#   На порту 80 у них развёрнут целый стек — как у тебя в FastAPI:
#
#   [ Браузер / наш сокет ]
#           │
#           │  TCP соединение на порт 80
#           ▼
#   [ Nginx — reverse proxy ]   ← принимает все входящие соединения
#           │
#           ▼
#   [ Uvicorn / Gunicorn ]      ← Python ASGI/WSGI сервер
#           │
#           ▼
#   [ FastAPI / Flask app ]     ← сам код httpbin.org
#           │
#           ▼
#       JSON ответ
#
#   Uvicorn, Nginx и любой другой сервер — в самом низу
#   работают с теми же сокетами, что мы изучаем сейчас.
#   Мы просто смотрим на это на уровень глубже.
# ─────────────────────────────────────────────────

sock.connect((HOST, PORT))
#
# ─────────────────────────────────────────────────
# connect() — подключаемся к серверу.
#
#   Почему двойные скобки (( ))?
#   connect() принимает ОДИН аргумент — кортеж (host, port):
#
#   sock.connect(  ("httpbin.org", 80)  )
#                 └──────────────────┘
#                      один кортеж
#
#   Внешние скобки — вызов функции.
#   Внутренние скобки — кортеж.
#
# ─────────────────────────────────────────────────
# Что происходит внутри connect():
#
#   1. DNS перевод:
#      "httpbin.org"  →  54.208.105.209
#
#   2. TCP рукопожатие (3 шага):
#
#      наш компьютер  ──── SYN ────►  httpbin.org
#      наш компьютер  ◄── SYN+ACK ──  httpbin.org
#      наш компьютер  ──── ACK ────►  httpbin.org
#
#      SYN = "хочу подключиться"
#      ACK = "принял, подтверждаю"
#
#   3. Соединение установлено ✅
#      Теперь можно отправлять данные.
# ─────────────────────────────────────────────────

request = "GET /get HTTP/1.1\r\nHost: httpbin.org\r\nConnection: close\r\n\r\n"
sock.sendall(request.encode("utf-8"))
#
# ─────────────────────────────────────────────────
# Что такое HTTP запрос?
#
#   HTTP — это просто текстовый протокол поверх TCP.
#   Браузер делает то же самое, просто скрывает это от тебя.
#
#   Наш запрос разобранный по частям:
#
#   "GET /get HTTP/1.1\r\n"
#     │    │      │     └─ \r\n = CRLF, разделитель строк в HTTP
#     │    │      └─ версия протокола
#     │    └─ путь на сервере (/get — эндпоинт httpbin.org)
#     └─ метод (GET = получить данные)
#
#   "Host: httpbin.org\r\n"
#     └─ обязательный заголовок — говорим серверу какой сайт хотим
#        (нужен потому что на одном IP может быть много сайтов)
#
#   "Connection: close\r\n"
#     └─ просим сервер закрыть соединение после ответа
#
#   "\r\n"
#     └─ пустая строка = конец заголовков (обязательно!)
#        После неё может идти тело запроса (для POST)
#
# ─────────────────────────────────────────────────
# encode("utf-8") — зачем?
#
#   Сокет работает только с байтами (bytes), не со строками (str).
#
#   "привет"            → строка Python (unicode)
#   "привет".encode()   → b'\xd0\xbf\xd1\x80...' (байты)
#
#   encode() = строка → байты   (перед отправкой)
#   decode() = байты → строка   (после получения)
#
# sendall() — отправляет ВСЕ байты.
#   Обычный send() может отправить только часть если буфер занят.
#   sendall() повторяет send() пока не отправит всё.
# ─────────────────────────────────────────────────

response = b""
while True:
    chunk = sock.recv(4096)
    if not chunk:
        break
    response += chunk
#
# ─────────────────────────────────────────────────
# Почему читаем в цикле, а не одним вызовом?
#
#   Данные по сети приходят КУСКАМИ, не все сразу.
#   Один вызов recv() даёт только то что пришло в данный момент.
#
#   Представь: сервер отправил 50 000 байт.
#   recv(4096) за раз читает максимум 4096 байт.
#   Нужно ~12 итераций цикла чтобы получить всё.
#
#   4096 — оптимальный размер буфера (кратен размеру
#   страницы памяти ОС = 4 КБ).
#
# ─────────────────────────────────────────────────
# if not chunk: break — зачем?
#
#   Когда сервер закончил отвечать — он закрывает соединение.
#   В этот момент recv() возвращает пустые байты: b""
#   b"" = False в Python → выходим из цикла.
#
#   Схема:
#
#   recv() → b"HTTP/1.1 200 OK..."  → данные есть, продолжаем
#   recv() → b"...json body..."     → данные есть, продолжаем
#   recv() → b""                    → соединение закрыто, break
#
# ─────────────────────────────────────────────────
# response = b"" — начинаем с пустых байт
#
#   response += chunk — добавляем каждый кусок к результату.
#   В конце цикла response содержит ПОЛНЫЙ ответ сервера.
# ─────────────────────────────────────────────────

print(response.decode("utf-8"))
#
# ─────────────────────────────────────────────────
# decode("utf-8") — обратная операция к encode()
#
#   response сейчас — байты (bytes)
#   decode() превращает байты обратно в строку чтобы можно было читать
#
#   encode() = строка → байты   (перед отправкой в сеть)
#   decode() = байты  → строка  (после получения из сети)
# ─────────────────────────────────────────────────

sock.close()
#
# ─────────────────────────────────────────────────
# close() — ОБЯЗАТЕЛЬНО закрывать сокет!
#
#   Каждый открытый сокет — это ресурс ОС (файловый дескриптор).
#   ОС даёт каждой программе лимит: ~1024 дескриптора.
#
#   Если не закрывать:
#   → "утечка ресурсов" (resource leak)
#   → при достижении лимита: "Too many open files" 💥
#
#   Лучший способ — использовать with, тогда close()
#   вызовется автоматически даже если произошла ошибка:
#
#   with socket.socket(AF_INET, SOCK_STREAM) as sock:
#       sock.connect((HOST, PORT))
#       ...
#   # ← sock.close() вызван автоматически здесь
# ─────────────────────────────────────────────────

# ─────────────────────────────────────────────────
