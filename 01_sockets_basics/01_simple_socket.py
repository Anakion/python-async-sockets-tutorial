#
#   HTTP/1.1 200 OK                        ← код ответа (200 = всё хорошо)
#   Date: Tue, 27 Oct 2026 11:24:14 GMT    ← дата и время ответа
#   Content-Type: application/json         ← тип данных в теле ответа
#   Content-Length: 199                    ← размер тела в байтах
#   Connection: close                      ← сервер закроет соединение
#   Server: gunicorn/19.9.0               ← видишь? у них Gunicorn!
#   Access-Control-Allow-Origin: *        ← CORS заголовок
#
#   {                                      ← тело ответа (JSON)
#     "args": {},
#     "headers": {
#       "Host": "httpbin.org"
#     },
#     "origin": "85.114.207.182",          ← твой внешний IP адрес
#     "url": "http://httpbin.org/get"      ← запрошенный URL
#   }
#
#   Мы сделали то что делает браузер — вручную,
#   через голый сокет, без requests и других библиотек!
