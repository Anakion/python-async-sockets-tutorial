# 02_two_sockets.py — сервер и клиент общаются друг с другом
#
#   Урок 1:  наш сокет ──► httpbin.org     (мы только клиент)
#   Урок 2:  наш сервер ◄══► наш клиент    (пишем ОБЕ стороны)


import socket  # уже знаем из урока 1 — работа с сетью
import threading
#
# ─────────────────────────────────────────────────
# Зачем threading?
#
#   Что такое accept()?
#
#   listen() только включает приём подключений.
#   Клиенты, вызвавшие connect(), попадают в ОЧЕРЕДЬ ОС:
#
#     клиент1, клиент2, клиент3  →  [ очередь ОС ]  →  accept()
#
#   accept() берёт ОДНОГО клиента из очереди и возвращает:
#
#     conn, addr = server_sock.accept()
#      │     └─ адрес клиента: ('127.0.0.1', 52924)
#      └─ НОВЫЙ сокет для обмена данными с ЭТИМ клиентом
#
#   server_sock — только принимает подключения.
#   conn        — через него делаем recv() / sendall().
#
#   Без accept() клиент висит в очереди,
#   а recv() / send() делать не через что.
#
#   accept() — БЛОКИРУЮЩИЙ вызов: если очередь пуста,
#   сервер стоит на этой строке, пока не подключится клиент.
#
#   Сервер и клиент в ОДНОМ файле, код идёт сверху вниз:
#     run_server()  ← зависнет на accept()
#     run_client()  ← никогда не выполнится
#
#   Программа зависает.
#
#   threading запускает run_server() и run_client()
#   в разных потоках, параллельно:
#     сервер блокируется на accept() в своём потоке,
#     а клиент в это время спокойно выполняет connect() в своём.
#
#   Это просто для удобства (запуск одной командой).
#   Можно без него: server.py и client.py в двух терминалах.
#
#   В реальных серверах threading нужен для другого —
#   обслуживать нескольких клиентов одновременно.
# ─────────────────────────────────────────────────

HOST = "127.0.0.1"
PORT = 65432
#
# ─────────────────────────────────────────────────
# HOST = "127.0.0.1" — localhost, адрес ЭТОГО же компьютера.
#
#   Урок 1:  HOST = "httpbin.org"  → чужой сервер в интернете
#   Урок 2:  HOST = "127.0.0.1"    → сервер на твоей машине
#
#   Данные не уходят в сеть — ОС передаёт их внутри себя
#   (loopback-интерфейс). Интернет не нужен.
#
#   "127.0.0.1"  → подключиться могут только программы этого компьютера
#   "0.0.0.0"    → подключиться может любое устройство в сети
#                  (телефон по Wi-Fi, другой ПК)
#
# ─────────────────────────────────────────────────
# PORT = 65432 — порт, на котором сервер ждёт подключений.
#
#   0–1023      → системные (80 HTTP, 22 SSH), нужны права админа
#   1024–65535  → свободны для наших программ
#
#   Если порт уже занят → ошибка "Address already in use".
#
# ─────────────────────────────────────────────────
# Кто использует HOST и PORT?
#
#   сервер:  bind((HOST, PORT))     ← занимает этот адрес
#   клиент:  connect((HOST, PORT))  ← подключается к этому адресу
#
#   У обоих должны быть ОДИНАКОВЫЕ HOST и PORT,
#   иначе клиент не найдёт сервер.
#
#   Порт клиента мы не задаём — ОС выдаёт случайный
#   (например 52924).
# ─────────────────────────────────────────────────

server_ready = threading.Event()
#
# ─────────────────────────────────────────────────
# threading.Event() — флаг, общий для потоков.
#
#   Проблема: потоки сервера и клиента стартуют почти
#   одновременно. Клиент может вызвать connect() РАНЬШЕ,
#   чем сервер сделает bind() + listen():
#
#     ConnectionRefusedError: [Errno 61] Connection refused
#     (на этом порту ещё никто не слушает)
#
#   Флаг имеет два состояния: False / True (изначально False).
#
#     сервер, после listen():   server_ready.set()   → флаг = True
#     клиент, перед connect():  server_ready.wait()  → ждёт, пока True
#
#   Поток сервера:  socket → bind → listen → set() ─────→ accept()...
#                                              │
#   Поток клиента:  wait() ...ждёт...ждёт... ──┴─→ connect() ✅
#
#   Если запускать в двух терминалах — Event не нужен:
#   ты сам сначала запускаешь сервер, потом клиента.
#
# ─────────────────────────────────────────────────
# ⚠️ Race condition (состояние гонки) 🏁
#
#   Даже если поток сервера стартует ПЕРВЫМ —
#   это НЕ значит, что он успеет дойти до listen().
#
#     server_thread.start()   # стартовал первым
#     client_thread.start()   # стартовал вторым
#
#   Кто когда работает — решает ОС (планировщик) 🧠,
#   а не порядок строк в коде.
#
#   ❌ БЕЗ Event — может случиться так:
#
#     🖥️ сервер:  socket() ... 💤 (ОС переключилась на клиента)
#     👤 клиент:  socket() → connect() 💥 ConnectionRefusedError
#     🖥️ сервер:  ... bind() → listen()   ← 🐢 поздно!
#
#   ✅ С Event — порядок гарантирован:
#
#     🖥️ сервер:  socket() → bind() → listen() → set() 🚩
#                                                  │
#     👤 клиент:  wait() ⏳ ...ждёт...ждёт... ──────┴─→ connect() 🤝
#
#   Event защищает не от "клиент запустился первым",
#   а от "клиент вызвал connect() ДО того, как сервер сделал listen()".
# ─────────────────────────────────────────────────


# ═════════════════════════════════════════════════
#                  🖥️  СЕРВЕР
# ═════════════════════════════════════════════════

def run_server():
    # ─────────────────────────────────────────────
    # Весь код сервера — в функции, чтобы потом
    # передать её в поток:
    #
    #   threading.Thread(target=run_server)
    #                           └─ какую функцию выполнять в потоке
    # ─────────────────────────────────────────────

    server_sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    #
    # ─────────────────────────────────────────────
    # Та же строка, что в уроке 1:
    #   AF_INET     → IPv4
    #   SOCK_STREAM → TCP
    #
    # Сокет при создании НЕ знает, сервер он или клиент.
    # Роль определяют методы, которые вызовем дальше:
    #
    #   👤 connect()                     → клиент  (урок 1)
    #   🖥️ bind() → listen() → accept()  → сервер  (сейчас)
    #
    # Почему имя server_sock, а не sock?
    #   У сервера скоро появится ВТОРОЙ сокет — conn (из accept()).
    #
    #   server_sock  → только принимает подключения 🚪
    #   conn         → через него идут данные 📨
    # ─────────────────────────────────────────────

    server_sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    #
    # ─────────────────────────────────────────────
    # SO_REUSEADDR — разрешить сразу повторно занять порт.
    #
    #   После close() ОС НЕ освобождает порт сразу —
    #   ~30–60 сек он в состоянии TIME_WAIT ⏳
    #   (вдруг по сети ещё летят опоздавшие пакеты).
    #
    #   Без этой опции повторный запуск скрипта:
    #     OSError: [Errno 48] Address already in use 💥
    #
    #   setsockopt(уровень, опция, значение)
    #     SOL_SOCKET   → опция уровня самого сокета (не TCP/IP)
    #     SO_REUSEADDR → какую опцию меняем
    #     1            → включить (0 = выключить)
    #
    #   ⚠️ Вызывать ДО bind() — именно bind() занимает порт.
    #
    #   Клиенту не нужно: у него каждый раз новый случайный порт.
    # ─────────────────────────────────────────────

    server_sock.bind((HOST, PORT))
    #
    # ─────────────────────────────────────────────
    # bind() — привязать сокет к адресу IP:порт 📌
    #
    #   Теперь ОС знает: все подключения на 127.0.0.1:65432
    #   отдавать ЭТОМУ сокету.
    #
    #   Двойные скобки — как у connect() в уроке 1:
    #
    #   server_sock.bind(  (HOST, PORT)  )
    #                      └──────────┘
    #                       один кортеж
    #
    #   Почему серверу bind() нужен, а клиенту нет?
    #
    #   🖥️ Сервер: адрес должен быть ИЗВЕСТЕН заранее,
    #              иначе клиент не знает, куда подключаться
    #              → bind((HOST, 65432))  ← сами выбираем порт
    #
    #   👤 Клиент: его адрес заранее никому не нужен
    #              → при connect() ОС сама даёт случайный порт
    #
    #   Ошибки:
    #     💥 Address already in use → порт занят
    #     💥 Permission denied      → порт < 1024 без прав админа
    #
    #   ⚠️ После bind() сокет ЕЩЁ НЕ принимает подключения —
    #      адрес закреплён, но слушать начнём в listen().
    # ─────────────────────────────────────────────

    server_sock.listen()
    #
    # ─────────────────────────────────────────────
    # listen() — режим приёма подключений 👂
    #
    #   С этого момента ОС САМА (без нашего кода)
    #   принимает входящих клиентов:
    #
    #   👤 клиент: connect()
    #         │
    #         ▼
    #   🧠 ОС: TCP-рукопожатие (SYN → SYN+ACK → ACK) 🤝
    #         │
    #         ▼
    #   📥 кладёт клиента в ОЧЕРЕДЬ (backlog)
    #         │
    #         ▼
    #   🖥️ наш код: accept() забирает из очереди
    #
    #   То есть клиент УЖЕ подключён (рукопожатие прошло),
    #   даже если мы ещё не вызвали accept() — он ждёт в очереди.
    #
    #   Аргумент backlog:
    #     listen()   → размер очереди по умолчанию (выбирает Python)
    #     listen(5)  → максимум 5 ждущих, остальным ОС откажет
    #
    #   ⚠️ Это НЕ лимит клиентов вообще — это сколько может
    #      ОДНОВРЕМЕННО ЖДАТЬ, пока мы не вызвали accept().
    # ─────────────────────────────────────────────

    print(f"[СЕРВЕР] Слушаю {HOST}:{PORT}...")
    # просто лог в консоль → [СЕРВЕР] Слушаю 127.0.0.1:65432...

    server_ready.set()
    #
    # ─────────────────────────────────────────────
    # Поднимаем флаг 🚩 — "я слушаю, можно подключаться".
    #
    #   Ставим ИМЕННО ПОСЛЕ listen():
    #   раньше — клиент получил бы ConnectionRefusedError 💥
    #   (race condition, см. выше).
    #
    #   👤 клиент на server_ready.wait() ⏳ → отпускается → connect()
    # ─────────────────────────────────────────────

    conn, addr = server_sock.accept()
    #
    # ─────────────────────────────────────────────
    # accept() — забрать клиента из очереди
    # (подробно про accept() — в шапке файла)
    #
    #   accept() возвращает кортеж из ДВУХ значений,
    #   сразу раскладываем его в две переменные:
    #
    #   conn, addr = server_sock.accept()
    #    │     └─ ('127.0.0.1', 52924)  ← IP и порт клиента
    #    └─ <socket ...>                ← НОВЫЙ сокет для этого клиента
    #
    #   То же самое, что:
    #     result = server_sock.accept()
    #     conn = result[0]
    #     addr = result[1]
    #
    #   Что происходит в этот момент:
    #
    #   🖥️ сервер: accept() ⏳ ...очередь пуста, ждёт...
    #   👤 клиент:            connect() ──► 🧠 ОС: рукопожатие 🤝 → 📥 очередь
    #   🖥️ сервер: accept() ✅ забрал клиента → conn, addr
    #
    #   Теперь у сервера ДВА сокета:
    #
    #   server_sock 🚪  127.0.0.1:65432           ← продолжает слушать порт
    #   conn        📨  связан с 127.0.0.1:52924  ← обмен данными с клиентом
    #
    #   ⚠️ Дальше recv() / sendall() — ТОЛЬКО через conn!
    # ─────────────────────────────────────────────

    print(f"[СЕРВЕР] Подключился клиент: {addr}")
    # → [СЕРВЕР] Подключился клиент: ('127.0.0.1', 52924)
    #   (порт случайный — у тебя будет другой)

    data = conn.recv(1024)
    #
    # ─────────────────────────────────────────────
    # recv(1024) — читаем данные от клиента 📥
    #
    #   ⚠️ У conn, а НЕ у server_sock!
    #   1024 — МАКСИМУМ байт за вызов, а не точное количество.
    #   БЛОКИРУЮЩИЙ: поток ждёт ⏳, пока клиент что-то пришлёт.
    #
    #   Почему один recv(), а не цикл как в уроке 1?
    #
    #   Урок 1:  while True: chunk = recv(4096) ... if not chunk: break
    #            → ответ большой, читаем пока сервер не закроет соединение
    #
    #   Урок 2:  data = recv(1024)  ← один раз
    #            → сообщение короткое (27 байт), влезает целиком
    #
    #   Цикл до b"" здесь ЗАВИС бы навсегда 😵:
    #   клиент ждёт наш ответ и соединение НЕ закрывает,
    #   значит recv() никогда не вернёт b"".
    #
    #   ⚠️ Это упрощение: TCP может разбить даже короткое
    #   сообщение на куски. Как с этим работать
    #   (длина сообщения, разделители) — в следующих уроках.
    # ─────────────────────────────────────────────

    message = data.decode("utf-8")
    # байты → строка (как в уроке 1)

    print(f"[СЕРВЕР] Получил: {message!r}")
    #
    # ─────────────────────────────────────────────
    # !r в f-строке — вывести через repr():
    #
    #   {message}    → Привет, сервер!
    #   {message!r}  → 'Привет, сервер!'   ← с кавычками
    #
    #   Удобно для отладки 🔍: видны кавычки, пробелы
    #   по краям и спецсимволы (\n, \r).
    # ─────────────────────────────────────────────

    reply = f"Привет, клиент! Ты прислал {len(data)} байт"
    #
    # ─────────────────────────────────────────────
    # len(data) vs len(message) — важная разница!
    #
    #   data    = b'\xd0\x9f\xd1\x80...'   ← байты
    #   message = 'Привет, сервер!'         ← строка
    #
    #   len(message) → 15  ← символов
    #   len(data)    → 27  ← байт
    #
    #   В UTF-8 кириллица = 2 байта на букву,
    #   латиница, пробел, знаки = 1 байт:
    #
    #   "Привет, сервер!"
    #    П р и в е т  ,  ␣  с е р в е р  !
    #    2 2 2 2 2 2  1  1  2 2 2 2 2 2  1   = 27 байт
    #    └── 12 русских букв × 2 = 24 ──┘ + 3 = 27
    #
    #   По сети идут БАЙТЫ — поэтому считаем байты.
    # ─────────────────────────────────────────────

    conn.sendall(reply.encode("utf-8"))
    #
    # ─────────────────────────────────────────────
    # Отправляем ответ клиенту 📤 (как в уроке 1):
    #   encode()  → строка → байты
    #   sendall() → отправит ВСЕ байты
    #
    #   ⚠️ Через conn, а НЕ через server_sock!
    #
    #   В этот момент recv() у клиента "просыпается" ⏰
    # ─────────────────────────────────────────────

    print("[СЕРВЕР] Отправил ответ")

    conn.close()
    server_sock.close()
    #
    # ─────────────────────────────────────────────
    # Закрываем ОБА сокета 🔒:
    #
    #   conn.close()         → разговор с ЭТИМ клиентом окончен 📨❌
    #   server_sock.close()  → больше не принимаем подключения 🚪❌
    #
    #   В реальном сервере всё иначе:
    #     server_sock живёт вечно (accept() в цикле) ♾️
    #     conn закрывается после каждого клиента
    #
    #     while True:
    #         conn, addr = server_sock.accept()
    #         ...общаемся...
    #         conn.close()
    #
    #   Это будет в следующих уроках.
    # ─────────────────────────────────────────────

    print("[СЕРВЕР] Закрыт")


# ═════════════════════════════════════════════════
#                  👤  КЛИЕНТ
# ═════════════════════════════════════════════════

def run_client():
    server_ready.wait()
    #
    # ─────────────────────────────────────────────
    # Ждём флаг 🚩 от сервера ⏳
    #
    #   Поток клиента стоит здесь, пока сервер
    #   не вызовет server_ready.set() (после listen()).
    #   Так мы избегаем race condition (см. выше).
    # ─────────────────────────────────────────────

    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as client_sock:
        #
        # ─────────────────────────────────────────
        # Создаём сокет клиента — та же строка, что у сервера.
        #
        # with — сокет закроется АВТОМАТИЧЕСКИ при выходе
        # из блока, даже если случилась ошибка 💥
        # (помнишь из урока 1? там мы писали close() вручную)
        #
        #   with socket.socket(...) as client_sock:
        #       ...
        #   # ← здесь client_sock.close() вызван сам
        # ─────────────────────────────────────────

        client_sock.connect((HOST, PORT))
        #
        # ─────────────────────────────────────────
        # connect() — подключаемся к серверу 🔌
        # (как в уроке 1, только HOST теперь наш)
        #
        #   👤 connect()  ──► 🧠 ОС: рукопожатие 🤝 ──► 📥 очередь
        #                                                │
        #   🖥️ accept() у сервера забирает нас ◄─────────┘
        #
        #   Здесь ОС выдаёт клиенту СЛУЧАЙНЫЙ порт (например 52924).
        # ─────────────────────────────────────────

        print(f"[КЛИЕНТ] Подключился. Мой адрес: {client_sock.getsockname()}")
        #
        # ─────────────────────────────────────────
        # getsockname() — "какой адрес у МОЕГО конца?"
        #   → ('127.0.0.1', 52924)  ← тот самый случайный порт
        #
        #   Он совпадает с addr, который получил сервер в accept()!
        #
        #   Соединение = ЧЕТЫРЕ числа:
        #     (IP клиента, порт клиента, IP сервера, порт сервера)
        #     ('127.0.0.1', 52924,       '127.0.0.1', 65432)
        #
        #   (getpeername() — адрес ДРУГОГО конца, т.е. сервера)
        # ─────────────────────────────────────────

        client_sock.sendall("Привет, сервер!".encode("utf-8"))
        print("[КЛИЕНТ] Отправил сообщение")
        #
        # ─────────────────────────────────────────
        # Отправляем 27 байт 📤
        #   В этот момент recv() у сервера "просыпается" ⏰
        # ─────────────────────────────────────────

        data = client_sock.recv(1024)
        #
        # ─────────────────────────────────────────
        # Ждём ответ сервера ⏳ (блокирующий вызов).
        #   Один recv() — ответ короткий, влезает целиком.
        # ─────────────────────────────────────────

        print(f"[КЛИЕНТ] Получил ответ: {data.decode('utf-8')!r}")

    print("[КЛИЕНТ] Закрыт")
    # ← мы вышли из with → client_sock уже закрыт автоматически


# ═════════════════════════════════════════════════
#                  🚀  ЗАПУСК
# ═════════════════════════════════════════════════

server_thread = threading.Thread(target=run_server)
client_thread = threading.Thread(target=run_client)
#
# ─────────────────────────────────────────────────
# Создаём два потока 🧵🧵
#
#   target=run_server — какую функцию выполнять в потоке.
#
#   ⚠️ БЕЗ скобок! Передаём САМУ функцию, а не вызываем её:
#     target=run_server    ✅ поток вызовет её сам
#     target=run_server()  ❌ вызовется сразу здесь и зависнет
#
#   Потоки созданы, но ещё НЕ запущены.
# ─────────────────────────────────────────────────

server_thread.start()
client_thread.start()
#
# ─────────────────────────────────────────────────
# start() — запустить поток ▶️
#
#   Функция начинает работать параллельно,
#   а основная программа СРАЗУ идёт дальше (не ждёт).
#
#   Теперь в программе 3 потока:
#     🧵 главный  → идёт к join()
#     🖥️ сервер   → socket → bind → listen → set() → accept() ⏳
#     👤 клиент   → wait() ⏳ → connect() → send → recv
# ─────────────────────────────────────────────────

server_thread.join()
client_thread.join()
#
# ─────────────────────────────────────────────────
# join() — дождаться завершения потока ⏳
#
#   Главный поток стоит здесь, пока сервер и клиент
#   не закончат работу.
#   Без join() "Готово!" напечаталось бы раньше,
#   чем потоки договорят.
# ─────────────────────────────────────────────────

print("Готово!")

